//! A record of a board that says which reel each part came from is only worth something if a change to it can be seen. This is the hash of the standard (FIPS 180-4) and the keyed hash
//! of RFC 2104, written out here so that the program needs nothing more to sign and to check a record. It is checked against the published test vectors.

