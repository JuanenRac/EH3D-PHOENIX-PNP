impl Text {
    /// How many words there are (the last variant, plus one).
    pub const COUNT: usize = Text::EditedNote as usize + 1;
}

/// The name of a language in that language.
pub fn lang_name(lang: Lang) -> &'static str {
    match lang {
        Lang::En => "English",
        Lang::Es => "Español",
        Lang::De => "Deutsch",
        Lang::Fr => "Français",
        Lang::It => "Italiano",
        Lang::Ja => "日本語",
        Lang::Zh => "中文",
        Lang::Pt => "Português",
    }
}

/// A word in a language.
pub fn tr(text: Text, lang: Lang) -> &'static str {
    TABLE[text as usize][lang as usize]
}

/// The whole table, one row per word and one column per language, for the tests.
pub fn table() -> &'static [[&'static str; 8]] {
    TABLE
}

